// The renderer gives what the Mustache specification gives for every case
// the JavaScript template depends on, including the removal of a line that
// holds only a section, inverted section, closing or comment tag, which the
// specification calls a standalone line.
func TestMustacheSpecification(t *testing.T) {
	for _, c := range mustacheSpecCases {
		t.Run(c.spec+"/"+c.name, func(t *testing.T) {
			got := parseMustache(c.template).render(c.data)
			if got != c.expected {
				t.Errorf("template %q gave %q, want %q", c.template, got,
					c.expected)
			}
		})
	}
}
